#!/usr/bin/env python3
"""Turn the SVG kits in art/ into kits.js.

Each kit file is one state of one piece (idle, selected, moving, attack, ...).
Class names, keyframe names and ids are prefixed per file so every state can
live in the same page without clashing. Run from the repo root:
    python3 tools/build_kits.py
"""
import json, os, re

KITS = {  # piece code -> (folder, file prefix)
    'wp': ('unit-p1-white-pawn', 'p1w-pawn-'),
    'wk': ('white-king', 'w-king-'),
    'wn': ('white-knight', 'w-knight-'),
    'wq': ('white-queen', 'w-queen-'),
    'wr': ('white-rook', 'w-rook-'),
}

def scope(svg, pre):
    css = ''.join(re.findall(r'<style>(.*?)</style>', svg, re.S))
    body = re.sub(r'<style>.*?</style>', '', svg, flags=re.S)
    body = re.sub(r'^.*?<svg[^>]*>', '', body, count=1, flags=re.S)
    body = re.sub(r'</svg>\s*$', '', body)
    body = re.sub(r'<title>.*?</title>', '', body, flags=re.S)
    css = re.sub(r'@media\s*\(prefers-reduced-motion[^{]*\{[^{}]*\{[^{}]*\}\s*\}', '', css)
    names = set(re.findall(r'@keyframes\s+([\w-]+)', css))
    def anim(m):
        v = m.group(2)
        for n in names:
            v = re.sub(r'(?<![\w-])' + re.escape(n) + r'(?![\w-])', pre + n, v)
        return m.group(1) + v
    css = re.sub(r'(animation(?:-name)?\s*:)([^;}]*)', anim, css)
    css = re.sub(r'@keyframes\s+([\w-]+)', lambda m: '@keyframes ' + pre + m.group(1), css)
    css = re.sub(r'\.([A-Za-z_][\w-]*)', lambda m: '.' + pre + m.group(1), css)
    body = re.sub(r'class="([^"]+)"', lambda m: 'class="' + ' '.join(pre + c for c in m.group(1).split()) + '"', body)
    body = re.sub(r'\bid="([^"]+)"', lambda m: 'id="' + pre + m.group(1) + '"', body)
    body = re.sub(r'url\(#([^)]+)\)', lambda m: 'url(#' + pre + m.group(1) + ')', body)
    body = re.sub(r'href="#([^"]+)"', lambda m: 'href="#' + pre + m.group(1) + '"', body)
    return css.strip(), body.strip()

out, css_all = {}, []
for code, (folder, fp) in KITS.items():
    out[code] = {}
    d = os.path.join('art', folder)
    for f in sorted(os.listdir(d)):
        if not f.startswith(fp) or not f.endswith('.svg'):
            continue
        state = f[len(fp):-4]
        if state == 'icon':
            continue
        css, body = scope(open(os.path.join(d, f)).read(), f'{code}-{state}-')
        css_all.append(css)
        out[code][state] = body
with open('kits.js', 'w') as fh:
    fh.write('// Generated by tools/build_kits.py from art/. Do not edit by hand.\n')
    fh.write('window.KIT_CSS=' + json.dumps('\n'.join(css_all)) + ';\n')
    fh.write('window.KITS=' + json.dumps(out) + ';\n')
print({k: sorted(v) for k, v in out.items()}, os.path.getsize('kits.js'))
